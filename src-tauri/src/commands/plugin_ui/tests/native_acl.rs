//! Resolve the build's real Tauri ACL, including the mapped HTTPS plugin origin.

use std::collections::BTreeMap;
use synra_ipc::{CommandRegistry, Interface};
use tauri::utils::{
    acl::{ExecutionContext, capability::Capability, manifest::Manifest, resolved::Resolved},
    platform::Target,
};

#[test]
fn native_acl_separates_host_and_plugin_commands_for_real_mapped_origins() {
    let manifests: BTreeMap<String, Manifest> = serde_json::from_str(
        &std::fs::read_to_string(concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/gen/schemas/acl-manifests.json"
        ))
        .expect("ACL generated by this native build"),
    )
    .expect("actual Tauri manifests");
    let capabilities: BTreeMap<String, Capability> = [
        include_str!("../../../../capabilities/default.json"),
        include_str!("../../../../capabilities/plugin-pages.json"),
    ]
    .into_iter()
    .map(|json| {
        let capability: Capability = serde_json::from_str(json).unwrap();
        (capability.identifier.clone(), capability)
    })
    .collect();
    let resolved = Resolved::resolve(&manifests, capabilities, Target::current())
        .expect("Tauri ACL resolution");
    assert!(resolved.has_app_acl);
    let id = super::plugin_id();
    let label = super::super::window_label_prefix(&id);
    let entry = super::super::origin::entry(&id, "index.html", None).unwrap();
    let mapped = entry.replacen("synra-plugin://", "https://synra-plugin.", 1);
    let allowed = |command: &str, label: &str, remote: Option<&str>| {
        resolved
            .allowed_commands
            .get(command)
            .is_some_and(|permissions| {
                permissions.iter().any(|permission| {
                    let origin = match (&permission.context, remote) {
                        (ExecutionContext::Local, None) => true,
                        (ExecutionContext::Remote { url }, Some(remote)) => {
                            url.test(&url::Url::parse(remote).unwrap())
                        }
                        _ => false,
                    };
                    origin
                        && permission
                            .windows
                            .iter()
                            .any(|pattern| pattern.matches(label))
                })
            })
    };
    for command in CommandRegistry::for_interface(Interface::Host) {
        assert!(allowed(command.name, "main", None), "{}", command.name);
        assert!(!allowed(command.name, &label, None), "{}", command.name);
        assert!(
            !allowed(command.name, &label, Some(&mapped)),
            "{}",
            command.name
        );
    }
    for command in CommandRegistry::for_interface(Interface::Plugin) {
        assert!(
            allowed(command.name, &label, Some(&mapped)),
            "{}",
            command.name
        );
        assert!(allowed(command.name, &label, None), "{}", command.name);
        assert!(!allowed(command.name, "main", None), "{}", command.name);
        assert!(
            !allowed(command.name, "other-window", Some(&mapped)),
            "{}",
            command.name
        );
        for remote in [
            "https://example.com/index.html",
            "http://synra-plugin.invalid.localhost/index.html",
        ] {
            assert!(
                !allowed(command.name, &label, Some(remote)),
                "{} {remote}",
                command.name
            );
        }
    }
}
